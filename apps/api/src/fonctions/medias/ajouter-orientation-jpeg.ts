export function ajouterOrientationJpeg(octets: Buffer, orientation: number): Buffer {
  const segment = Buffer.from([
    0xff, 0xe1, 0x00, 0x22, 0x45, 0x78, 0x69, 0x66, 0x00, 0x00,
    0x4d, 0x4d, 0x00, 0x2a, 0x00, 0x00, 0x00, 0x08,
    0x00, 0x01, 0x01, 0x12, 0x00, 0x03, 0x00, 0x00, 0x00, 0x01, 0x00, orientation, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00,
  ]);
  const apresJfif = octets[2] === 0xff && octets[3] === 0xe0 ? 4 + ((octets[4]! << 8) | octets[5]!) : 2;
  return Buffer.concat([octets.subarray(0, apresJfif), segment, octets.subarray(apresJfif)]);
}
