// Le schéma d'une base PGlite relevé objet par objet (tables, colonnes, index, contraintes, types énumérés, fonctions,
// déclencheurs), et ce qui change entre deux relevés : ce qu'une migration ajoute, retire ou modifie (règle des migrations
// additives), et ce qui passe sur la base d'essai (vide) mais échouera sur une table remplie.
// Les colonnes sont lues dans pg_attribute : le type exact (format_type : « character varying(80) », « numeric(10,2) »,
// « text[] », le nom d'un type énuméré), NOT NULL, le défaut (pg_get_expr), l'identité, une colonne calculée, la collation.
// Un rétrécissement (varchar(80) → varchar(40)), un défaut ou un NOT NULL qui change se voient donc tous. Les NOT NULL sont
// lus sur les colonnes (PostgreSQL 18 les range aussi parmi les contraintes, type « n » : écartées).
import type { PGlite } from "@electric-sql/pglite";

/** « colonne avis.statut » → « text NOT NULL DEFAULT 'publie'::text » ; « table avis » → « » ; « index avis.avis_pkey » → sa définition */
export type Schema = Map<string, string>;

const TABLES = `c.relnamespace = 'public'::regnamespace AND c.relkind IN ('r', 'p')`;

const RELEVE = `
  SELECT 'table ' || c.relname AS cle, '' AS valeur FROM pg_class c WHERE ${TABLES}
  UNION ALL SELECT 'colonne ' || c.relname || '.' || a.attname,
    format_type(a.atttypid, a.atttypmod)
      || CASE WHEN a.attcollation <> t.typcollation THEN ' COLLATE ' || quote_ident(co.collname) ELSE '' END
      || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END
      || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
      || CASE WHEN a.attgenerated <> '' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ')'
              ELSE COALESCE(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), '') END
    FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_type t ON t.oid = a.atttypid
    LEFT JOIN pg_collation co ON co.oid = a.attcollation LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE ${TABLES} AND a.attnum > 0 AND NOT a.attisdropped
  UNION ALL SELECT 'index ' || tablename || '.' || indexname, indexdef FROM pg_indexes WHERE schemaname = 'public'
  UNION ALL SELECT 'contrainte ' || c.relname || '.' || k.conname, pg_get_constraintdef(k.oid)
    FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid WHERE k.connamespace = 'public'::regnamespace AND k.contype <> 'n'
  UNION ALL SELECT 'type ' || t.typname, string_agg(e.enumlabel, ', ' ORDER BY e.enumsortorder)
    FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid WHERE t.typnamespace = 'public'::regnamespace GROUP BY t.typname
  UNION ALL SELECT 'fonction ' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid)
    FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace AND p.prokind IN ('f', 'p')
  UNION ALL SELECT 'déclencheur ' || c.relname || '.' || g.tgname, pg_get_triggerdef(g.oid)
    FROM pg_trigger g JOIN pg_class c ON c.oid = g.tgrelid WHERE NOT g.tgisinternal`;

export async function lireSchema(db: PGlite): Promise<Schema> {
  const lignes = (await db.query(RELEVE)).rows as { cle: string; valeur: string }[];
  return new Map(lignes.map((l) => [l.cle, l.valeur]));
}

export type Changements = {
  ajouts: string[];
  retraits: string[];
  modifications: string[];
  /** Ce qui passe sur la base d'essai (vide) mais échouera si une table qui existait a des lignes qui ne s'y plient pas */
  risques: string[];
};

/** La table d'une colonne, d'un index, d'une contrainte ou d'un déclencheur (« colonne avis.note » → « avis ») */
const tableDe = (cle: string) => /^(?:colonne|index|contrainte|déclencheur) ([^.]+)\./.exec(cle)?.[1];

/** Une colonne relevée, en morceaux : son type (collation comprise), NOT NULL, et si la base la remplit seule (défaut,
 *  identité ou calcul) ; « character varying(80) NOT NULL DEFAULT 'x'::character varying » → type « character varying(80) » */
const lireColonne = (definition: string) => {
  const [, type, nonNul, remplie] = /^(.*?)( NOT NULL)?((?: DEFAULT| GENERATED) .*)?$/s.exec(definition)!;
  return { type: type!, nonNul: nonNul !== undefined, remplie: remplie !== undefined };
};

const SORTES_CONTRAINTES: [RegExp, string][] = [[/^CHECK /, "CHECK"], [/^UNIQUE /, "UNIQUE"], [/^FOREIGN KEY /, "clé étrangère"], [/^PRIMARY KEY /, "clé primaire"], [/^EXCLUDE /, "EXCLUDE"]];

/** Pourquoi `cle` (ajoutée ou modifiée, sur une table qui existait) peut échouer sur des lignes existantes ; null si rien */
function risqueDe(cle: string, avant: string | undefined, apres: string, nouvellesContraintes: Set<string>): string | null {
  if (cle.startsWith("colonne ")) {
    const nouvelle = lireColonne(apres);
    if (avant === undefined) return nouvelle.nonNul && !nouvelle.remplie ? "NOT NULL sans défaut (échouera si la table a des lignes)" : null;
    const ancienne = lireColonne(avant);
    const morceaux: string[] = [];
    if (ancienne.type !== nouvelle.type) morceaux.push(`type ${ancienne.type} → ${nouvelle.type} (échouera si une valeur existante n'y rentre pas ou ne s'y convertit pas)`);
    if (!ancienne.nonNul && nouvelle.nonNul) morceaux.push("devient NOT NULL (échouera si une ligne y a NULL)");
    return morceaux.length > 0 ? morceaux.join(" ; ") : null;
  }
  // Une contrainte NOT VALID ne vérifie pas les lignes déjà là
  if (cle.startsWith("contrainte ") && !apres.endsWith(" NOT VALID")) {
    const sorte = SORTES_CONTRAINTES.find(([motif]) => motif.test(apres))?.[1];
    return sorte ? `${sorte} ${avant === undefined ? "ajoutée" : "changée"} : ${apres}` : null;
  }
  // L'index d'une contrainte UNIQUE ou de clé primaire porte son nom : signalé une fois, avec elle
  if (cle.startsWith("index ") && /^CREATE UNIQUE INDEX /.test(apres) && !nouvellesContraintes.has(cle.replace(/^index /, "contrainte "))) {
    return `index UNIQUE ${avant === undefined ? "ajouté" : "changé"} (échouera s'il y a des doublons) : ${apres}`;
  }
  return null;
}

export function comparerSchemas(avant: Schema, apres: Schema): Changements {
  const ajouts = [...apres.keys()].filter((cle) => !avant.has(cle)).sort();
  const modifiees = [...avant.keys()].filter((cle) => apres.has(cle) && apres.get(cle) !== avant.get(cle)).sort();
  const nouvellesContraintes = new Set([...ajouts, ...modifiees].filter((cle) => cle.startsWith("contrainte ")));
  const risques = [...ajouts, ...modifiees].sort().flatMap((cle) => {
    const table = tableDe(cle);
    if (table === undefined || !avant.has(`table ${table}`)) return [];
    const pourquoi = risqueDe(cle, avant.get(cle), apres.get(cle) ?? "", nouvellesContraintes);
    return pourquoi ? [`${cle} : ${pourquoi}`] : [];
  });
  return {
    ajouts,
    retraits: [...avant.keys()].filter((cle) => !apres.has(cle)).sort(),
    // Le corps d'une fonction tient sur des dizaines de lignes : on dit seulement qu'il change
    modifications: modifiees.map((cle) => (cle.startsWith("fonction ") ? `${cle} : sa définition change`
      : `${cle} : ${avant.get(cle) || "(rien)"} → ${apres.get(cle) || "(rien)"}`)),
    risques,
  };
}

/** Les ajouts en quelques lignes : les tables nouvelles nommées (leurs colonnes, index, contraintes et déclencheurs comptés avec elles) */
export function resumerAjouts(ajouts: string[]): string[] {
  const tables = new Set(ajouts.filter((cle) => cle.startsWith("table ")).map((cle) => cle.slice(6)));
  const avecElles = ajouts.filter((cle) => !cle.startsWith("table ") && tables.has(tableDe(cle) ?? ""));
  const compter = (sorte: string) => avecElles.filter((cle) => cle.startsWith(`${sorte} `)).length;
  const detail = ["colonne", "index", "contrainte", "déclencheur"].filter((sorte) => compter(sorte) > 0).map((sorte) => `${sorte} : ${compter(sorte)}`).join(", ");
  const lignes = tables.size > 0 ? [`table(s) ${[...tables].join(", ")} (${detail})`] : [];
  return [...lignes, ...ajouts.filter((cle) => !cle.startsWith("table ") && !tables.has(tableDe(cle) ?? ""))];
}
