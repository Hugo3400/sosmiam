// Le schéma d'une base PGlite relevé objet par objet (tables, colonnes, index, contraintes, types énumérés, fonctions,
// déclencheurs), et ce qui change entre deux relevés : ce qu'une migration ajoute, retire ou modifie (règle des migrations
// additives), et ce qui passe sur la base d'essai (vide) mais échouera sur une table remplie.
// Les colonnes sont lues dans pg_attribute : le type exact (format_type : « character varying(80) », « numeric(10,2) »,
// « text[] », le nom d'un type énuméré), NOT NULL, le défaut (pg_get_expr), l'identité, une colonne calculée, la collation.
// Un rétrécissement (varchar(80) → varchar(40)), un défaut ou un NOT NULL qui change se voient donc tous. Les NOT NULL sont
// lus sur les colonnes (PostgreSQL 18 les range aussi parmi les contraintes, type « n » : écartées).
import type { PGlite } from "@electric-sql/pglite";
import { decouperInstructions } from "./decouper-instructions.ts";

export type ObjetSchema = {
  definition: string;
  identite: string | null;
  colonnes: string[] | null;
  lignesExistantesRemplies: boolean;
};

/** « colonne avis.statut » → « text NOT NULL DEFAULT 'publie'::text » ; « table avis » → « » ; « index avis.avis_pkey » → sa définition */
export type Schema = Map<string, ObjetSchema>;

const TABLES = `c.relnamespace = 'public'::regnamespace AND c.relkind IN ('r', 'p')`;

const nomsDesColonnes = (table: string, numeros: string, filtre = "true") => `array_to_json(ARRAY(SELECT a.attname
  FROM unnest(${numeros}) WITH ORDINALITY u(numero, rang) JOIN pg_attribute a ON a.attrelid = ${table} AND a.attnum = u.numero
  WHERE ${filtre} ORDER BY u.rang))::text`;

const RELEVE = `
  SELECT 'table ' || c.relname AS cle, '' AS valeur, c.oid::text AS identite, NULL AS colonnes, 'false' AS remplie
    FROM pg_class c WHERE ${TABLES}
  UNION ALL SELECT 'colonne ' || c.relname || '.' || a.attname,
    format_type(a.atttypid, a.atttypmod)
      || CASE WHEN a.attcollation <> t.typcollation THEN ' COLLATE ' || quote_ident(co.collname) ELSE '' END
      || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END
      || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY' WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
      || CASE WHEN a.attgenerated <> '' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ')'
              ELSE COALESCE(' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid), '') END,
    c.oid::text || '.' || a.attnum, NULL, a.atthasmissing::text
    FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid JOIN pg_type t ON t.oid = a.atttypid
    LEFT JOIN pg_collation co ON co.oid = a.attcollation LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
    WHERE ${TABLES} AND a.attnum > 0 AND NOT a.attisdropped
  UNION ALL SELECT 'index ' || c.relname || '.' || i.relname, pg_get_indexdef(i.oid), NULL,
    ${nomsDesColonnes("x.indrelid", "x.indkey::int2[]", "u.rang <= x.indnkeyatts")}, 'false'
    FROM pg_index x JOIN pg_class c ON c.oid = x.indrelid JOIN pg_class i ON i.oid = x.indexrelid
    WHERE c.relnamespace = 'public'::regnamespace AND c.relkind IN ('r', 'm', 'p') AND i.relkind IN ('i', 'I')
  UNION ALL SELECT 'contrainte ' || c.relname || '.' || k.conname, pg_get_constraintdef(k.oid), NULL,
    ${nomsDesColonnes("k.conrelid", "k.conkey")}, 'false'
    FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid WHERE k.connamespace = 'public'::regnamespace AND k.contype <> 'n'
  UNION ALL SELECT 'type ' || t.typname, string_agg(e.enumlabel, ', ' ORDER BY e.enumsortorder), NULL, NULL, 'false'
    FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid WHERE t.typnamespace = 'public'::regnamespace GROUP BY t.typname
  UNION ALL SELECT 'fonction ' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')', pg_get_functiondef(p.oid), NULL, NULL, 'false'
    FROM pg_proc p WHERE p.pronamespace = 'public'::regnamespace AND p.prokind IN ('f', 'p')
  UNION ALL SELECT 'déclencheur ' || c.relname || '.' || g.tgname, pg_get_triggerdef(g.oid), NULL, NULL, 'false'
    FROM pg_trigger g JOIN pg_class c ON c.oid = g.tgrelid WHERE NOT g.tgisinternal`;

type LigneReleve = { cle: string; valeur: string; identite: string | null; colonnes: string | null; remplie: string };

export async function lireSchema(db: PGlite): Promise<Schema> {
  const lignes = (await db.query(RELEVE)).rows as LigneReleve[];
  return new Map(lignes.map((l) => [l.cle, {
    definition: l.valeur,
    identite: l.identite,
    colonnes: l.colonnes === null ? null : (JSON.parse(l.colonnes) as string[]),
    lignesExistantesRemplies: l.remplie === "true",
  }]));
}

export type Changements = {
  ajouts: string[];
  retraits: string[];
  modifications: string[];
  /** Ce qui passe sur la base d'essai (vide) mais échouera si une table qui existait a des lignes qui ne s'y plient pas */
  risques: string[];
};

/** La table d'une colonne, d'un index, d'une contrainte ou d'un déclencheur (« colonne avis.note » → « avis ») */
const tableDe = (cle: string) => /^(?:colonne|index|contrainte|déclencheur) ([^.]+)\./.exec(cle)?.[1];

/** Une colonne relevée, en morceaux : son type (collation comprise), NOT NULL, et si la base la remplit seule (défaut,
 *  identité ou calcul) ; « character varying(80) NOT NULL DEFAULT 'x'::character varying » → type « character varying(80) » */
const lireColonne = (definition: string) => {
  const [, type, nonNul, remplie] = /^(.*?)( NOT NULL)?((?: DEFAULT| GENERATED) .*)?$/s.exec(definition)!;
  return { type: type!, nonNul: nonNul !== undefined, remplie: remplie !== undefined };
};

const ENTIERS = ["smallint", "integer", "bigint"];

/** varchar(40) → varchar(80), varchar ou text : aucune valeur existante ne peut casser */
const elargit = (avant: string, apres: string) => {
  if (ENTIERS.includes(avant) && ENTIERS.includes(apres)) return ENTIERS.indexOf(apres) >= ENTIERS.indexOf(avant);
  const taille = (type: string) => /^character varying(?:\((\d+)\))?$/.exec(type);
  const de = taille(avant);
  if (de === null) return false;
  if (apres === "text" || apres === "character varying") return true;
  const vers = taille(apres)?.[1];
  return de[1] !== undefined && vers !== undefined && Number(vers) >= Number(de[1]);
};

/** Les contraintes qui vérifient les lignes déjà là (une NOT VALID ne les vérifie pas) */
const VERIFIE_LES_LIGNES = /^(CHECK|UNIQUE|FOREIGN KEY|PRIMARY KEY|EXCLUDE) (?!.* NOT VALID$)/s;

const NOM_DE_TABLE = String.raw`(?:ONLY\s+)?(?:(?:"[^"]+"|[A-Za-z_][\w$]*)\s*\.\s*)?(?:"([^"]+)"|([A-Za-z_][\w$]*))`;
const ECRITURE = new RegExp(String.raw`(?<!\b(?:ON|DO)\s+)\b(?:UPDATE|INSERT\s+INTO|MERGE\s+INTO|COPY)\s+${NOM_DE_TABLE}`, "gi");
const CONVERSION = new RegExp(String.raw`^ALTER\s+TABLE\s+(?:IF\s+EXISTS\s+)?${NOM_DE_TABLE}[\s\S]*\bUSING\b`, "i");

const nomLu = (entre: string | undefined, nu: string | undefined) => entre ?? nu!.toLowerCase();

function tablesRempliesPar(sql: string): Set<string> {
  const ecrites = [...sql.matchAll(ECRITURE)].map((m) => nomLu(m[1], m[2]));
  const converties = decouperInstructions(sql).flatMap((i) => {
    const m = CONVERSION.exec(i.texte);
    return m ? [nomLu(m[1], m[2])] : [];
  });
  return new Set([...ecrites, ...converties]);
}

const resteNulleAuxLignes = (colonne: ObjetSchema) => {
  const { nonNul, remplie } = lireColonne(colonne.definition);
  return !nonNul && !remplie && !colonne.lignesExistantesRemplies;
};

function poseeSurColonneNulle(table: string, objet: ObjetSchema, nulles: Set<string>): boolean {
  const surNulle = (objet.colonnes ?? []).map((colonne) => nulles.has(`${table}.${colonne}`));
  if (/^FOREIGN KEY /.test(objet.definition)) {
    return / MATCH FULL\b/.test(objet.definition) ? surNulle.length > 0 && surNulle.every(Boolean) : surNulle.some(Boolean);
  }
  if (/^(UNIQUE |CREATE UNIQUE INDEX )/.test(objet.definition)) return !/ NULLS NOT DISTINCT\b/.test(objet.definition) && surNulle.some(Boolean);
  return false;
}

type Contexte = { table: string; contraintesChangees: Set<string>; colonnesNulles: Set<string> };

/** Pourquoi `cle` (ajoutée ou modifiée, sur une table qui existait) peut échouer sur des lignes existantes ; null si rien */
function risqueDe(cle: string, avant: string | undefined, apres: ObjetSchema, contexte: Contexte): string | null {
  const geste = avant === undefined ? "ajouté" : "changé";
  if (cle.startsWith("colonne ")) {
    const nouvelle = lireColonne(apres.definition);
    if (avant === undefined) return nouvelle.nonNul && !nouvelle.remplie ? "NOT NULL sans défaut (échouera si la table a des lignes)" : null;
    const ancienne = lireColonne(avant);
    const morceaux: string[] = [];
    if (ancienne.type !== nouvelle.type && !elargit(ancienne.type, nouvelle.type)) {
      morceaux.push(`type ${ancienne.type} → ${nouvelle.type} (échouera si une valeur existante n'y rentre pas ou ne s'y convertit pas)`);
    }
    if (!ancienne.nonNul && nouvelle.nonNul) morceaux.push("devient NOT NULL (échouera si une ligne y a NULL)");
    return morceaux.length > 0 ? morceaux.join(" ; ") : null;
  }
  if (poseeSurColonneNulle(contexte.table, apres, contexte.colonnesNulles)) return null;
  if (cle.startsWith("contrainte ")) return VERIFIE_LES_LIGNES.test(apres.definition) ? `${geste}e : ${apres.definition}` : null;
  // L'index d'une contrainte UNIQUE ou de clé primaire porte son nom : signalé une fois, avec elle
  if (cle.startsWith("index ") && /^CREATE UNIQUE INDEX /.test(apres.definition) && !contexte.contraintesChangees.has(cle.replace(/^index /, "contrainte "))) {
    return `${geste} : ${apres.definition.replace(/^CREATE UNIQUE INDEX \S+ ON \S+ USING btree /, "UNIQUE ")}`;
  }
  return null;
}

export function comparerSchemas(avant: Schema, apres: Schema, sql = ""): Changements {
  const definition = (schema: Schema, cle: string) => schema.get(cle)?.definition;
  const communes = [...avant.keys()].filter((cle) => apres.has(cle));
  const recreees = communes.filter((cle) => avant.get(cle)!.identite !== apres.get(cle)!.identite);
  const tablesRecreees = new Set(recreees.filter((cle) => cle.startsWith("table ")).map((cle) => cle.slice("table ".length)));
  const recreeesSeules = new Set(recreees.filter((cle) => !tablesRecreees.has(tableDe(cle) ?? "")));
  const ajouts = [...apres.keys()].filter((cle) => !avant.has(cle)).sort();
  const modifiees = communes.filter((cle) => recreeesSeules.has(cle) || definition(apres, cle) !== definition(avant, cle)).sort();
  const tableExistait = (table: string | undefined): table is string => table !== undefined && avant.has(`table ${table}`) && !tablesRecreees.has(table);
  const colonnesNouvelles = new Set([...ajouts, ...recreeesSeules].filter((cle) => cle.startsWith("colonne ")));
  const tablesRemplies = tablesRempliesPar(sql);
  const colonnesNulles = new Set([...colonnesNouvelles]
    .filter((cle) => tableExistait(tableDe(cle)) && !tablesRemplies.has(tableDe(cle)!) && resteNulleAuxLignes(apres.get(cle)!))
    .map((cle) => cle.slice("colonne ".length)));
  const contraintesChangees = new Set([...ajouts, ...modifiees].filter((cle) => cle.startsWith("contrainte ")));
  const risques = [...ajouts, ...modifiees].sort().flatMap((cle) => {
    const table = tableDe(cle);
    if (!tableExistait(table)) return [];
    const ancienne = colonnesNouvelles.has(cle) ? undefined : definition(avant, cle);
    const pourquoi = risqueDe(cle, ancienne, apres.get(cle)!, { table, contraintesChangees, colonnesNulles });
    return pourquoi ? [`${cle} : ${pourquoi}`] : [];
  });
  const decrireModification = (cle: string) => {
    const de = definition(avant, cle) || "(rien)";
    const vers = definition(apres, cle) || "(rien)";
    if (recreeesSeules.has(cle)) return `${cle} : effacée puis recréée${de === vers ? "" : ` (${de} → ${vers})`} : ses valeurs sont perdues`;
    // Le corps d'une fonction tient sur des dizaines de lignes : on dit seulement qu'il change
    return cle.startsWith("fonction ") ? `${cle} : sa définition change` : `${cle} : ${de} → ${vers}`;
  };
  return {
    ajouts,
    retraits: [...avant.keys()].filter((cle) => !apres.has(cle)).sort(),
    modifications: modifiees.map(decrireModification),
    risques,
  };
}

/** Les ajouts en quelques lignes : les tables nouvelles nommées (leurs colonnes, index, contraintes et déclencheurs comptés avec elles) */
export function resumerAjouts(ajouts: string[]): string[] {
  const tables = new Set(ajouts.filter((cle) => cle.startsWith("table ")).map((cle) => cle.slice(6)));
  const avecElles = ajouts.filter((cle) => !cle.startsWith("table ") && tables.has(tableDe(cle) ?? ""));
  const compter = (sorte: string) => avecElles.filter((cle) => cle.startsWith(`${sorte} `)).length;
  const detail = ["colonne", "index", "contrainte", "déclencheur"].filter((sorte) => compter(sorte) > 0).map((sorte) => `${sorte} : ${compter(sorte)}`).join(", ");
  const lignes = tables.size > 0 ? [`table(s) ${[...tables].join(", ")} (${detail})`] : [];
  return [...lignes, ...ajouts.filter((cle) => !cle.startsWith("table ") && !tables.has(tableDe(cle) ?? ""))];
}
